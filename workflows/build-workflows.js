// Generates n8n workflow JSON (workflows/dist) and the organization seed SQL (db/generated).
// Usage: node workflows/build-workflows.js
const fs = require('fs');
const path = require('path');
const { departments, employees } = require('./src/organization');
const buildEmployeeWorkflow = require('./src/employee-workflow');
const builders = [
  require('./src/planning-workflow'),
  require('./src/dispatcher-workflow'),
  require('./src/task-runner-workflow'),
  require('./src/review-workflow'),
  require('./src/dashboard-api-workflow'),
  require('./src/linkedin-publisher-workflow'),
  require('./src/integration-check-workflow'),
  require('./src/architecture-overview-workflow'),
];

const root = path.join(__dirname, '..');
const distDir = path.join(__dirname, 'dist');
const seedDir = path.join(root, 'db', 'generated');

const ids = new Set();
for (const e of employees) {
  for (const f of ['employee_id', 'employee_name', 'department_id', 'job_title', 'description', 'workflow_id',
                   'skills', 'input_schema', 'output_schema', 'system_message', 'validate', 'postprocess']) {
    if (!e[f]) throw new Error(`employee ${e.employee_id || '?'} is missing ${f}`);
  }
  if (!departments.some((d) => d.department_id === e.department_id)) throw new Error(`${e.employee_id}: unknown department`);
  if (ids.has(e.employee_id)) throw new Error(`duplicate employee ${e.employee_id}`);
  ids.add(e.employee_id);
}

fs.rmSync(distDir, { recursive: true, force: true });
fs.mkdirSync(distDir, { recursive: true });
const workflows = [...builders.map((b) => b()), ...employees.map(buildEmployeeWorkflow)];
for (const wf of workflows) {
  fs.writeFileSync(path.join(distDir, `${wf.id}.json`), `${JSON.stringify(wf, null, 2)}\n`);
}

const lit = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const json = (v) => `${lit(JSON.stringify(v))}::jsonb`;
const sql = [
  '-- GENERATED by workflows/build-workflows.js from workflows/src/organization.js. Do not edit by hand.',
  'BEGIN;',
  ...departments.map((d) => `INSERT INTO wf.departments (department_id, name, purpose) VALUES (${lit(d.department_id)}, ${lit(d.name)}, ${lit(d.purpose)})
  ON CONFLICT (department_id) DO UPDATE SET name = EXCLUDED.name, purpose = EXCLUDED.purpose, updated_at = now();`),
  ...employees.map((e) => `INSERT INTO wf.employees (employee_id, employee_name, department_id, job_title, description, input_schema, output_schema, workflow_reference)
  VALUES (${lit(e.employee_id)}, ${lit(e.employee_name)}, ${lit(e.department_id)}, ${lit(e.job_title)}, ${lit(e.description)}, ${json(e.input_schema)}, ${json(e.output_schema)}, ${lit(e.workflow_id)})
  ON CONFLICT (employee_id) DO UPDATE SET employee_name = EXCLUDED.employee_name, department_id = EXCLUDED.department_id,
    job_title = EXCLUDED.job_title, description = EXCLUDED.description, input_schema = EXCLUDED.input_schema,
    output_schema = EXCLUDED.output_schema, workflow_reference = EXCLUDED.workflow_reference, updated_at = now();`),
  `DELETE FROM wf.employee_skills WHERE employee_id IN (${employees.map((e) => lit(e.employee_id)).join(', ')});`,
  ...employees.flatMap((e) => e.skills.map((s) => `INSERT INTO wf.employee_skills (employee_id, skill_name, description) VALUES (${lit(e.employee_id)}, ${lit(s.skill_name)}, ${lit(s.description)});`)),
  'COMMIT;',
  '',
].join('\n');
fs.mkdirSync(seedDir, { recursive: true });
fs.writeFileSync(path.join(seedDir, 'seed-organization.sql'), sql);

console.log(`built ${workflows.length} workflows -> ${path.relative(root, distDir)}`);
console.log(`seeded ${departments.length} departments, ${employees.length} employees -> db/generated/seed-organization.sql`);
