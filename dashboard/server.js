// Dashboard server: serves the static UI and proxies /api/* to the n8n workforce webhooks.
// The API key (env WORKFORCE_API_KEY, else ../.env) is added server-side, so it never reaches the browser.
// /api/integrations* (settings page) is handled by ./integrations.js: secrets go straight to n8n credentials.
// Usage: node dashboard/server.js   (or the "dashboard" service in docker-compose.yml), then open http://localhost:3000
const http = require('http');
const fs = require('fs');
const path = require('path');

const PORT = Number(process.env.DASHBOARD_PORT || 3000);
const HOST = process.env.DASHBOARD_HOST || '127.0.0.1';
const N8N_BASE = process.env.N8N_WEBHOOK_BASE || 'http://127.0.0.1:5678/webhook/workforce';
const PUBLIC_DIR = path.join(__dirname, 'public');
// Images generated by the Visual Design employee (shared volume with n8n), served at /assets/*
const ASSETS_DIR = path.resolve(process.env.ASSETS_DIR || path.join(__dirname, '..', 'data', 'assets'));
const MAX_BODY = 1024 * 1024;

function readEnvFile() {
  try {
    return Object.fromEntries(fs.readFileSync(path.join(__dirname, '..', '.env'), 'utf8')
      .split(/\r?\n/).filter((l) => l.includes('=')).map((l) => [l.slice(0, l.indexOf('=')), l.slice(l.indexOf('=') + 1)]));
  } catch {
    return {};
  }
}
const API_KEY = process.env.WORKFORCE_API_KEY || readEnvFile().WORKFORCE_API_KEY;
if (!API_KEY) throw new Error('WORKFORCE_API_KEY is not set (env var or .env)');

// Only the workforce endpoints can be reached through the proxy.
const ALLOWED = new Set(['requests', 'organization', 'plans', 'plan', 'plan/history', 'plan/deliverables', 'approvals',
  'plan/cancel', 'task/retry', 'approval/decision', 'task/direct', 'results/recent', 'task/output',
  'plan/publications', 'plan/publish-linkedin', 'library', 'library/status', 'integrations/test']);

const TYPES = { '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8', '.js': 'text/javascript; charset=utf-8',
                '.svg': 'image/svg+xml', '.ico': 'image/x-icon', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.png': 'image/png' };

const send = (res, status, body, type = 'application/json; charset=utf-8') => {
  res.writeHead(status, { 'content-type': type, 'cache-control': 'no-store' });
  res.end(body);
};

async function readBody(req) {
  const chunks = [];
  let size = 0;
  for await (const c of req) {
    size += c.length;
    if (size > MAX_BODY) throw Object.assign(new Error('too large'), { code: 'too_large' });
    chunks.push(c);
  }
  try { return JSON.parse(Buffer.concat(chunks).toString('utf8') || '{}'); } catch { return {}; }
}
const integrations = require('./integrations')({ n8nWebhookBase: N8N_BASE, apiKey: API_KEY, send, readBody });

async function proxy(req, res, endpoint, search) {
  if (!ALLOWED.has(endpoint)) return send(res, 404, JSON.stringify({ ok: false, error: { code: 'not_found', message: 'unknown endpoint' } }));
  const chunks = [];
  let size = 0;
  for await (const c of req) {
    size += c.length;
    if (size > MAX_BODY) return send(res, 413, JSON.stringify({ ok: false, error: { code: 'too_large', message: 'request body over 1 MB' } }));
    chunks.push(c);
  }
  try {
    const upstream = await fetch(`${N8N_BASE}/${endpoint}${search}`, {
      method: req.method,
      headers: { 'X-API-Key': API_KEY, 'content-type': 'application/json' },
      body: req.method === 'GET' ? undefined : Buffer.concat(chunks),
      signal: AbortSignal.timeout(300000),
    });
    send(res, upstream.status, await upstream.text());
  } catch (e) {
    send(res, 503, JSON.stringify({ ok: false, error: { code: 'n8n_unavailable', message: `n8n is not reachable: ${e.message}` } }));
  }
}

http.createServer((req, res) => {
  const url = new URL(req.url, 'http://localhost');
  if (url.pathname.startsWith('/api/')) {
    const endpoint = url.pathname.slice(5);
    return integrations(req, res, endpoint).then((handled) => (handled ? undefined : proxy(req, res, endpoint, url.search)));
  }
  if (req.method !== 'GET') return send(res, 405, 'method not allowed', 'text/plain');
  const isAsset = url.pathname.startsWith('/assets/');
  const root = isAsset ? ASSETS_DIR : PUBLIC_DIR;
  const rel = isAsset ? url.pathname.slice('/assets/'.length) : (url.pathname === '/' ? 'index.html' : url.pathname);
  const file = path.normalize(path.join(root, decodeURIComponent(rel)));
  if (!file.startsWith(root + path.sep)) return send(res, 403, 'forbidden', 'text/plain');
  fs.readFile(file, (err, data) => (err ? send(res, 404, 'not found', 'text/plain')
    : send(res, 200, data, TYPES[path.extname(file)] || 'application/octet-stream')));
}).listen(PORT, HOST, () => console.log(`Dashboard: http://localhost:${PORT}  (proxy -> ${N8N_BASE})`));
